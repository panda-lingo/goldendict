import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = resolve(
  packageRoot,
  "compatibility/goldendict-ng.json",
);
const generatedCssPath = resolve(
  packageRoot,
  "src/styles/vendor.generated.ts",
);
const args = process.argv.slice(2);
const checking = args.includes("--check");

function option(name) {
  const index = args.indexOf(name);
  return index >= 0 ? args[index + 1] : undefined;
}

function fail(message) {
  process.stderr.write(`goldendict sync: ${message}\n`);
  process.exitCode = 1;
}

function sha256Text(value) {
  return createHash("sha256").update(value).digest("hex");
}

function git(sourceRoot, args) {
  return execFileSync("git", ["-C", sourceRoot, ...args], {
    encoding: "utf8",
  }).trim();
}

function normalizeRemote(remote) {
  const ssh = /^git@([^:]+):(.+?)(?:\.git)?$/.exec(remote);
  if (ssh) {
    return `https://${ssh[1]}/${ssh[2].replace(/\.git$/, "")}`;
  }
  return remote.replace(/\.git$/, "");
}

function sourceProvenance(sourceRoot, currentManifest) {
  const trackedSources = currentManifest.files.map((entry) => entry.source);
  const status = git(sourceRoot, [
    "status",
    "--porcelain=v1",
    "--",
    ...trackedSources,
  ]);
  const diff = git(sourceRoot, ["diff", "--binary", "HEAD", "--", ...trackedSources]);
  let remote = currentManifest.sourceRepository;
  try {
    remote = normalizeRemote(git(sourceRoot, ["remote", "get-url", "origin"]));
  } catch {
    // A local checkout without an origin is still reproducible by commit and
    // the per-file hashes, so retain the previously declared repository.
  }
  return {
    repository: remote,
    commit: git(sourceRoot, ["rev-parse", "HEAD"]),
    dirty: status.length > 0,
    diffSha256: sha256Text(diff),
  };
}

async function checksum(path) {
  const content = await readFile(path);
  return createHash("sha256").update(content).digest("hex");
}

async function generatedCssModule(currentManifest) {
  const styles = {};
  for (const entry of currentManifest.files) {
    if (
      entry.target.startsWith("src/styles/vendor/") &&
      entry.target.endsWith(".css")
    ) {
      const fileName = entry.target.split("/").at(-1);
      styles[fileName] = await readFile(resolve(packageRoot, entry.target), "utf8");
    }
  }
  const styleNames = Object.keys(styles)
    .map((fileName) => JSON.stringify(fileName))
    .join(" | ");
  return `// Generated by scripts/sync-goldendict.mjs. Do not edit.\nexport type GoldenDictVendorStylesheet = ${styleNames};\nexport const GOLDENDICT_VENDOR_CSS: Readonly<Record<GoldenDictVendorStylesheet, string>> = ${JSON.stringify(styles)};\n`;
}

const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const sourceOption = option("--source");
const sourceRoot = sourceOption ? resolve(sourceOption) : undefined;

if (!checking && !sourceRoot) {
  fail("sync requires --source /path/to/goldendict-ng");
} else {
  let mismatch = false;
  let provenance;
  if (sourceRoot) {
    try {
      provenance = sourceProvenance(sourceRoot, manifest);
    } catch {
      fail("--source must be a Git checkout so its provenance can be pinned");
      mismatch = true;
    }
  }
  for (const entry of manifest.files) {
    const targetPath = resolve(packageRoot, entry.target);
    if (checking) {
      try {
        const targetHash = await checksum(targetPath);
        if (targetHash !== entry.sha256) {
          fail(`${entry.target} differs from its pinned checksum`);
          mismatch = true;
        }
      } catch (error) {
        fail(`${entry.target} cannot be checked: ${error.message}`);
        mismatch = true;
      }
      if (sourceRoot) {
        try {
          const sourceHash = await checksum(resolve(sourceRoot, entry.source));
          if (sourceHash !== entry.sha256) {
            fail(`${entry.source} in --source differs from the pinned version`);
            mismatch = true;
          }
        } catch (error) {
          fail(`${entry.source} cannot be checked: ${error.message}`);
          mismatch = true;
        }
      }
      continue;
    }

    const sourcePath = resolve(sourceRoot, entry.source);
    await mkdir(dirname(targetPath), { recursive: true });
    await copyFile(sourcePath, targetPath);
    entry.sha256 = await checksum(targetPath);
  }

  if (!checking) {
    if (!provenance) {
      fail("source provenance could not be read");
      process.exitCode = 1;
      process.exit();
    }
    manifest.sourceRepository = provenance.repository;
    manifest.sourceCommit = provenance.commit;
    manifest.sourceDirty = provenance.dirty;
    manifest.sourceDiffSha256 = provenance.diffSha256;
    await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
    await writeFile(generatedCssPath, await generatedCssModule(manifest));
    process.stdout.write(
      `Synced ${manifest.files.length} GoldenDict-ng files at ${manifest.sourceCommit}.\n`,
    );
  } else {
    if (sourceRoot && provenance) {
      for (const [field, actual, expected] of [
        ["commit", provenance.commit, manifest.sourceCommit],
        ["repository", provenance.repository, manifest.sourceRepository],
        ["dirty state", provenance.dirty, manifest.sourceDirty ?? false],
        ["diff hash", provenance.diffSha256, manifest.sourceDiffSha256 ?? sha256Text("")],
      ]) {
        if (actual !== expected) {
          fail(`--source ${field} differs from the pinned provenance`);
          mismatch = true;
        }
      }
    }
    try {
      const expectedGeneratedCss = await generatedCssModule(manifest);
      const actualGeneratedCss = await readFile(generatedCssPath, "utf8");
      if (actualGeneratedCss !== expectedGeneratedCss) {
        fail("src/styles/vendor.generated.ts is stale; run sync:goldendict");
        mismatch = true;
      }
    } catch (error) {
      fail(`generated CSS module cannot be checked: ${error.message}`);
      mismatch = true;
    }
  }
  if (checking && !mismatch) {
    process.stdout.write(
      `Verified ${manifest.files.length} GoldenDict-ng files at ${manifest.sourceCommit}.\n`,
    );
  }
}
